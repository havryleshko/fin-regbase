#!/usr/bin/env node
import { readdirSync, readFileSync, writeFileSync, mkdirSync, statSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const repoRoot = resolve(__dirname, "..", "..");
const wikiRoot = resolve(repoRoot, "wiki");
const generatedPath = resolve(__dirname, "..", "lib", "site-metrics.generated.ts");

const COUNTED_DIRS = ["concepts", "summaries", "derived"];

function countMarkdownFiles(dir) {
  let total = 0;
  try {
    for (const entry of readdirSync(dir, { withFileTypes: true })) {
      if (entry.isFile() && entry.name.endsWith(".md")) total += 1;
    }
  } catch {
    return 0;
  }
  return total;
}

function deriveArticleCount() {
  return COUNTED_DIRS.reduce((sum, d) => sum + countMarkdownFiles(join(wikiRoot, d)), 0);
}

const MONTHS = [
  "January", "February", "March", "April", "May", "June",
  "July", "August", "September", "October", "November", "December",
];

function deriveLastUpdated() {
  const logPath = join(wikiRoot, "log.md");
  let dateString;
  try {
    const log = readFileSync(logPath, "utf8");
    const matches = [...log.matchAll(/^##\s*\[(\d{4})-(\d{2})-(\d{2})\]/gm)];
    if (matches.length > 0) {
      const last = matches[matches.length - 1];
      dateString = `${last[1]}-${last[2]}-${last[3]}`;
    }
  } catch {
    // fall through to mtime
  }
  if (!dateString) {
    let latestMs = 0;
    for (const d of COUNTED_DIRS) {
      const dirPath = join(wikiRoot, d);
      try {
        for (const entry of readdirSync(dirPath, { withFileTypes: true })) {
          if (!entry.isFile() || !entry.name.endsWith(".md")) continue;
          const fullPath = join(dirPath, entry.name);
          const stat = statSync(fullPath);
          if (stat.mtimeMs > latestMs) latestMs = stat.mtimeMs;
        }
      } catch {
        // skip missing dirs
      }
    }
    if (latestMs === 0) {
      const now = new Date();
      return `${MONTHS[now.getMonth()]} ${now.getFullYear()}`;
    }
    const d = new Date(latestMs);
    return `${MONTHS[d.getMonth()]} ${d.getFullYear()}`;
  }
  const [y, m] = dateString.split("-");
  return `${MONTHS[Number(m) - 1]} ${y}`;
}

const articleCount = deriveArticleCount();
const lastUpdated = deriveLastUpdated();

const banner = "// AUTO-GENERATED by scripts/gen-site-metrics.mjs. Do not edit by hand.\n";
const body = `export const generatedSiteMetrics = {
  articleCount: ${articleCount},
  lastUpdated: ${JSON.stringify(lastUpdated)},
} as const;
`;

mkdirSync(dirname(generatedPath), { recursive: true });
writeFileSync(generatedPath, banner + body, "utf8");

process.stdout.write(
  `[gen-site-metrics] articleCount=${articleCount} lastUpdated="${lastUpdated}"\n`,
);
